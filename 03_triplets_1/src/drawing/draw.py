import math, os, sys
from PIL import Image, ImageDraw

S = 4
N = 250
LW = 3.0


def ap(cx, cy, rx, ry, a0, a1, n=48):
    out = []
    for i in range(n + 1):
        a = math.radians(a0 + (a1 - a0) * i / n)
        out.append((cx + rx * math.cos(a), cy + ry * math.sin(a)))
    return out


def cr(pts, closed=False, n=10):
    m = len(pts)
    out = []
    rng = range(m) if closed else range(m - 1)
    for i in rng:
        p1 = pts[i]
        p2 = pts[(i + 1) % m]
        p0 = pts[(i - 1) % m] if (closed or i > 0) else p1
        p3 = pts[(i + 2) % m] if (closed or i + 2 < m) else p2
        for t in range(n):
            u = t / n
            x = 0.5 * ((2 * p1[0]) + (-p0[0] + p2[0]) * u + (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * u * u + (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * u ** 3)
            y = 0.5 * ((2 * p1[1]) + (-p0[1] + p2[1]) * u + (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * u * u + (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * u ** 3)
            out.append((x, y))
    if not closed:
        out.append(pts[-1])
    return out


class Cv:
    def __init__(s):
        s.im = Image.new("L", (N * S, N * S), 255)
        s.d = ImageDraw.Draw(s.im)
        s.T = None

    def tf(s, ox, oy, ang=0, sc=1):
        s.T = (ox, oy, math.radians(ang), sc)

    def off(s):
        s.T = None

    def _p(s, pts):
        out = []
        for x, y in pts:
            if s.T:
                ox, oy, a, sc = s.T
                ca, sa = math.cos(a), math.sin(a)
                x, y = ox + sc * (x * ca - y * sa), oy + sc * (x * sa + y * ca)
            out.append((x * S, y * S))
        return out

    def L(s, pts, w=LW):
        q = s._p(pts)
        s.d.line(q, fill=0, width=int(w * S), joint="curve")
        r = w * S / 2
        for x, y in (q[0], q[-1]):
            s.d.ellipse((x - r, y - r, x + r, y + r), fill=0)

    def P(s, pts, f=True, w=LW):
        q = s._p(pts)
        if f:
            s.d.polygon(q, fill=0 if f == "k" else 255)
        s.d.line(q + [q[0], q[1]], fill=0, width=int(w * S), joint="curve")

    def SM(s, pts, closed=False, f=False):
        q = cr(pts, closed)
        if closed:
            s.P(q, f)
        else:
            s.L(q)

    def E(s, x0, y0, x1, y1, f=True):
        s.P(ap((x0 + x1) / 2, (y0 + y1) / 2, (x1 - x0) / 2, (y1 - y0) / 2, 0, 360, 64)[:-1], f)

    def R(s, x0, y0, x1, y1, r=0, f=True):
        if r == 0:
            pts = [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]
        else:
            pts = (ap(x1 - r, y0 + r, r, r, 270, 360, 8) + ap(x1 - r, y1 - r, r, r, 0, 90, 8) +
                   ap(x0 + r, y1 - r, r, r, 90, 180, 8) + ap(x0 + r, y0 + r, r, r, 180, 270, 8))
        s.P(pts, f)

    def A(s, cx, cy, rx, ry, a0, a1):
        s.L(ap(cx, cy, rx, ry, a0, a1))

    def D(s, x, y, r=3.5):
        q = s._p([(x, y)])[0]
        rr = r * S
        s.d.ellipse((q[0] - rr, q[1] - rr, q[0] + rr, q[1] + rr), fill=0)

    def union(s, circles):
        w = LW / 2
        for (x, y, r) in circles:
            q = s._p([(x, y)])[0]
            sc = s.T[3] if s.T else 1
            rr = (r * sc + w) * S
            s.d.ellipse((q[0] - rr, q[1] - rr, q[0] + rr, q[1] + rr), fill=0)
        for (x, y, r) in circles:
            q = s._p([(x, y)])[0]
            sc = s.T[3] if s.T else 1
            rr = (r * sc - w) * S
            s.d.ellipse((q[0] - rr, q[1] - rr, q[0] + rr, q[1] + rr), fill=255)


def cyl(c, cx, top, rx, ry, h):
    pts = [(cx - rx, top)] + ap(cx, top + h, rx, ry, 180, 0)[::-1][::-1]
    pts = [(cx - rx, top)] + ap(cx, top + h, rx, ry, 180, 0) + [(cx + rx, top)]
    # ap from 180 to 0 goes through 90? use explicit lower half
    low = ap(cx, top + h, rx, ry, 0, 180)[::-1]
    c.P([(cx - rx, top)] + low + [(cx + rx, top)])
    c.E(cx - rx, top - ry, cx + rx, top + ry)


